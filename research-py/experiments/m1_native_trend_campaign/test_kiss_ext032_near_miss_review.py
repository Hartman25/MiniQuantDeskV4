def test_the_attempt_status_must_agree_with_the_registry(w):
    def with_attempts(attempts):
        reg = copy.deepcopy(w.registry)
        reg["attempts"][w.ids["SPY"]] = attempts
        return trial(w.review(registry=reg), "SPY")

    assert with_attempts([{"attempt_index": 1, "status": "succeeded"}])["final_status"] == nm.WITHHELD
    assert with_attempts([{"attempt_index": 1, "status": "started"}])["final_status"] == nm.INVALID
    assert with_attempts([{"attempt_index": 1, "status": "failed"}])["final_status"] == nm.INVALID
    assert with_attempts([{"attempt_index": 2, "status": "succeeded"}])["final_status"] == nm.INVALID
    assert with_attempts([])["final_status"] == nm.INVALID
    retried = with_attempts([{"attempt_index": 1, "status": "failed"}, {"attempt_index": 2, "status": "failed"}])
    assert retried["final_status"] == nm.INVALID
    rows = copy.deepcopy(w.rows)
    rows[0].update(economic_failed="boom", attempt_index=None, judge_status="excluded:no_successful_attempt")
    j = copy.deepcopy(w.judge)
    j["included_trial_ids"].remove(w.ids["SPY"])
    j["excluded_trial_ids"].append({"trial_id": w.ids["SPY"], "reason": "no_successful_attempt"})
    j["dsr_results"] = [x for x in j["dsr_results"] if x["trial_id"] != w.ids["SPY"]]
    reg = copy.deepcopy(w.registry)
    reg["attempts"][w.ids["SPY"]] = [{"attempt_index": 1, "status": "failed"}]
    t = trial(w.review(rows=rows, judge=j, registry=reg), "SPY")
    assert t["final_status"] == nm.UNQUALIFIED and t["evaluability"] == "ECONOMIC_ATTEMPT_FAILED"
    reg["attempts"][w.ids["SPY"]] = [{"attempt_index": 1, "status": "succeeded"}]
    assert trial(w.review(rows=rows, judge=j, registry=reg), "SPY")["final_status"] == nm.INVALID


