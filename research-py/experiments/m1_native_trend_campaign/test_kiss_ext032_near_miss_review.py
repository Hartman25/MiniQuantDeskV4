def trial(report, symbol):
    return next(t for t in report["trials"] if t["symbol"] == symbol)


def gate(t, name):
    return next(g for g in t["gates"] if g["gate"] == name)


def statuses(report):
    return {t["symbol"]: t["final_status"] for t in report["trials"]}


