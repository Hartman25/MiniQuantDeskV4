def test_the_judge_inventory_must_partition_exactly_the_recomputed_ids(w):
    def broken(mutate):
        j = copy.deepcopy(w.judge)
        mutate(j)
        return w.review(judge=j)

    r = broken(lambda j: j["included_trial_ids"].pop())
    assert r["judge"]["inventory"]["status"] == "MISMATCH"
    assert "DOES_NOT_ACCOUNT" in " ".join(t["reason_codes"][0] for t in r["trials"] if t["final_status"] == nm.INVALID) or \
        any(t["final_status"] == nm.INVALID for t in r["trials"])
    r = broken(lambda j: j["included_trial_ids"].append("ff" * 16))
    assert any("JUDGE_INVENTORY_DIFFERS_FROM_EXPECTED" in p for p in r["judge"]["inventory"]["problems"])
    r = broken(lambda j: j["included_trial_ids"].append(j["included_trial_ids"][0]))
    assert "JUDGE_INVENTORY_HAS_DUPLICATES" in r["judge"]["inventory"]["problems"]
    r = broken(lambda j: j["excluded_trial_ids"].append({"trial_id": j["included_trial_ids"][0], "reason": "x"}))
    assert "JUDGE_TRIAL_BOTH_INCLUDED_AND_EXCLUDED" in r["judge"]["inventory"]["problems"]
    r = broken(lambda j: j["registry_population"].update(registered_unique_trials=3))
    assert any("REGISTRY_POPULATION" in p for p in r["judge"]["inventory"]["problems"])
    r = broken(lambda j: j["scope"].update(hypothesis_id="h"))
    assert "JUDGE_SCOPE_IS_NOT_THE_WHOLE_EXPERIMENT" in r["judge"]["inventory"]["problems"]
    r = broken(lambda j: j["scope"].update(experiment_id="OTHER"))
    assert "JUDGE_SCOPE_IS_NOT_THE_WHOLE_EXPERIMENT" in r["judge"]["inventory"]["problems"]
    r = broken(lambda j: j["holdout"].update(status="consumed"))
    assert "JUDGE_HOLDOUT_STATUS_NOT_RESERVED" in r["judge"]["inventory"]["problems"]
    r = broken(lambda j: j.update(included_trial_ids="not-a-list"))
    assert r["judge"]["inventory"]["status"] == "MISMATCH"
    for rep in (broken(lambda j: j["included_trial_ids"].pop()), broken(lambda j: j["scope"].update(experiment_id="OTHER"))):
        assert "JUDGE_INVENTORY_NOT_VERIFIED" in rep["qualification_blockers"]
        assert not {t["final_status"] for t in rep["trials"]} & set(NEVER_QUALIFYING)


